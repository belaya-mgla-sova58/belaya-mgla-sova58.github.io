/* Generate a conservative, homepage-specific CSS bundle from the shared stylesheet.
 * This removes ONLY complete rules whose every selector is explicitly scoped
 * to body.is-<other>-route. The shared stylesheet remains unchanged for all
 * other pages. No dependencies, no class-name guessing, no style reordering.
 *
 * Build: node scripts/build-home-css.cjs
 * Check: node scripts/build-home-css.cjs --check
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const INPUT = path.join(ROOT, 'site-v626.min.css');
const OUTPUT = path.join(ROOT, 'site-home-v995.css');
const HEADER = '/* Generated by scripts/build-home-css.cjs. Edit site-v626.min.css, then regenerate. */\n';

function selectors(text) {
  const out = [];
  let part = '', depth = 0, brackets = 0, quote = '';
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      part += c;
      if (c === '\\' && i + 1 < text.length) part += text[++i];
      else if (c === quote) quote = '';
      continue;
    }
    if (c === '"' || c === "'") { quote = c; part += c; continue; }
    if (c === '(') depth++;
    else if (c === ')') depth--;
    else if (c === '[') brackets++;
    else if (c === ']') brackets--;
    if (c === ',' && depth === 0 && brackets === 0) {
      out.push(part.trim());
      part = '';
    } else part += c;
  }
  out.push(part.trim());
  return out;
}

function firstSelectorCharacter(css, start, end) {
  let i = start;
  while (i < end) {
    if (/\s/.test(css[i])) { i++; continue; }
    if (css.slice(i, i + 2) === '/*') {
      const commentEnd = css.indexOf('*/', i + 2);
      if (commentEnd < 0 || commentEnd >= end) throw Error('Unclosed selector comment');
      i = commentEnd + 2;
      continue;
    }
    break;
  }
  return i;
}

// Remove only comments and whitespace that cannot affect selector/value semantics.
// Preserve spaces inside strings, functions (including calc/url), and selector chains.
function compact(css) {
  let out = '', quote = '', escaped = false, comment = false, parens = 0;
  for (let i = 0; i < css.length; i++) {
    const ch = css[i], next = css[i + 1];
    if (comment) {
      if (ch === '*' && next === '/') { comment = false; i++; }
      continue;
    }
    if (quote) {
      out += ch;
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = '';
      continue;
    }
    if (ch === '/' && next === '*') { comment = true; i++; continue; }
    if (ch === '"' || ch === "'") { quote = ch; out += ch; continue; }
    if (ch === '(') parens++;
    else if (ch === ')') parens = Math.max(0, parens - 1);
    if (/\\s/.test(ch) && parens === 0) {
      let j = i + 1;
      while (j < css.length && /\\s/.test(css[j])) j++;
      const previous = out.slice(-1), following = css[j] || '';
      if (!previous || !following || previous === '{' || previous === '}' ||
          previous === ';' || following === '{' || following === '}' ||
          following === ';') { i = j - 1; continue; }
      out += ' ';
      i = j - 1;
      continue;
    }
    out += ch;
  }
  if (quote || comment || parens) throw Error('Cannot safely compact unterminated CSS');
  return out;
}

function build(css) {
  const stack = [], blocks = [];
  let start = 0, quoted = '', comment = false, parens = 0, brackets = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i], next = css[i + 1];
    if (comment) {
      if (c === '*' && next === '/') { comment = false; i++; }
      continue;
    }
    if (quoted) {
      if (c === '\\') { i++; continue; }
      if (c === quoted) quoted = '';
      continue;
    }
    if (c === '/' && next === '*') { comment = true; i++; continue; }
    if (c === '"' || c === "'") { quoted = c; continue; }
    if (c === '(') { parens++; continue; }
    if (c === ')') { parens--; continue; }
    if (c === '[') { brackets++; continue; }
    if (c === ']') { brackets--; continue; }
    if (c === '{' && !parens && !brackets) {
      const head = css.slice(start, i).replace(/\/\*[\s\S]*?\*\//g, '').trim();
      if (stack.length) stack[stack.length - 1].children++;
      stack.push({ head, start, children: 0 });
      start = i + 1;
    } else if (c === '}' && !parens && !brackets) {
      const block = stack.pop();
      if (!block) throw Error('Unmatched CSS closing brace');
      if (!block.children) {
        blocks.push({
          ...block,
          end: i + 1,
          insideKeyframes: stack.some(parent => /^@(?:-\w+-)?keyframes\b/i.test(parent.head)),
        });
      }
      start = i + 1;
    }
  }
  if (stack.length || quoted || comment || parens || brackets)
    throw Error('Unbalanced CSS: unable to safely generate home bundle');

  // Requiring a body route class at the *start* of every selector guarantees
  // it cannot match the homepage, whose body class is is-home-route.
  const exclusivelyNonhome = /^body\.is-(?!home-route\b)[a-z0-9-]+-route\b/i;
  const removals = [];
  for (const rule of blocks) {
    if (rule.insideKeyframes || rule.head.startsWith('@')) continue;
    const parts = selectors(rule.head);
    if (!parts.length || parts.some(sel => /:not\(/i.test(sel))) continue;
    if (!parts.every(sel => exclusivelyNonhome.test(sel))) continue;
    const ruleStart = firstSelectorCharacter(css, rule.start, rule.end);
    if (ruleStart >= rule.end) throw Error('Invalid rule at ' + rule.start);
    removals.push({ start: ruleStart, end: rule.end, selector: rule.head });
  }
  removals.sort((a,b) => a.start-b.start);
  for (let i=1; i<removals.length; i++) {
    if (removals[i].start < removals[i - 1].end)
      throw Error('Overlapping CSS removals');
  }
  const removedBytes=removals.reduce((sum,r) => sum+(r.end-r.start), 0);
  if (removals.length < 250 || removedBytes < 40000)
    throw Error('Unexpectedly few nonhome rules: review generator before release');
  let out=css;
  for (const rule of removals.slice().reverse())
    out=out.slice(0, rule.start)+out.slice(rule.end);
  return { content: HEADER + compact(out), removedRules: removals.length, removedBytes };
}

const css = fs.readFileSync(INPUT, 'utf8');
const home = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const body = home.match(/<body\b[^>]*class="([^"]+)"/i)?.[1] || '';
if (!body.split(/\s+/).includes('is-home-route') ||
    body.split(/\s+/).some(token => /^is-(?!home-route$)[\w-]+-route$/.test(token)))
  throw Error('Homepage body route changed: review generated CSS assumptions');
const output = build(css);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8') !== output.content)
    throw Error('site-home-v995.css is stale: run node scripts/build-home-css.cjs');
  console.log('Home CSS up-to-date:',output.removedRules,'rules,',output.removedBytes,'bytes omitted');
} else {
  fs.writeFileSync(OUTPUT, output.content);
  console.log('Home CSS generated:', output.removedRules,'rules,',output.removedBytes,'bytes omitted');
}
